"""Runs scenarios through the real workflow and writes docs/test_matrix.md + .csv.
Expected values are written HERE by hand (from the policy), not read from agent output."""
import copy, sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))
import pandas as pd
from invoiceguard.data_gen import generate_dataset
from invoiceguard.orchestrator import FAULT_PERSISTENT, FAULT_TRANSIENT, process_invoice
from invoiceguard.tools import load_policy

ds, pol = generate_dataset(42), load_policy()
def pick(a): return next(i for i in ds["invoices"] if ds["ground_truth"][i["invoice_id"]]["anomaly"] == a)
def mod(a, **kw):
    i = copy.deepcopy(pick(a)); i.update(kw); return i

S = []  # (scenario, input description, invoice, fault, expected decision, expected status, expected critic attempts)
for a, desc, dec in [("CLEAN", "all lines match PO & GRN, bank/GST ok, < limit", "APPROVE"),
                     ("PRICE_TOL", "unit price +1% (tolerance 2%)", "APPROVE"),
                     ("PRICE_OVER", "unit price +8..15%", "HOLD"), ("QTY_OVER", "billed qty > received qty", "PAY_PARTIAL"),
                     ("NO_GRN", "PO exists, no goods receipt", "HOLD"), ("DUPLICATE", "same vendor+number, different format", "REJECT"),
                     ("BANK_CHANGE", "bank account differs from vendor master", "ESCALATE"), ("TAX_MISMATCH", "GST rate wrong for vendor", "HOLD"),
                     ("NO_PO", "no PO reference", "HOLD"), ("HIGH_VALUE", "clean but payable > INR 5,00,000", "ESCALATE"),
                     ("ARITH_ERROR", "declared total 5% off", "HOLD"), ("MULTI_BANK_QTY", "bank change + over-billing", "ESCALATE"),
                     ("MULTI_DUP_PRICE", "duplicate + price over", "REJECT")]:
    st = "AUTO_APPROVED_SIMULATED" if dec == "APPROVE" else "PENDING_HUMAN_REVIEW"
    S.append((f"{a} ({ds['ground_truth'][pick(a)['invoice_id']]['label']})", desc, pick(a), None, dec, st, 1))
S += [("Missing invoice number + qty 0", "invoice_no='' and qty=0", mod("CLEAN", invoice_no="", lines=[{**pick("CLEAN")["lines"][0], "qty": 0}]), None, "HOLD", "PENDING_HUMAN_REVIEW", 1),
      ("Bad date", "invoice_date='31/13/2026'", mod("CLEAN", invoice_date="31/13/2026"), None, "HOLD", "PENDING_HUMAN_REVIEW", 1),
      ("PO reference not in system", "po_id='PO-9999'", mod("CLEAN", po_id="PO-9999"), None, "HOLD", "PENDING_HUMAN_REVIEW", 1),
      ("Fault: transient wrong payable", "QTY_OVER + inflate_payable on attempt 1", pick("QTY_OVER"), FAULT_TRANSIENT, "PAY_PARTIAL", "PENDING_HUMAN_REVIEW", 2),
      ("Fault: transient on clean invoice", "CLEAN + inflate_payable on attempt 1", pick("CLEAN"), FAULT_TRANSIENT, "APPROVE", "AUTO_APPROVED_SIMULATED", 2),
      ("Fault: persistent wrong approval", "DUPLICATE + force_approve on both attempts", pick("DUPLICATE"), FAULT_PERSISTENT, "ESCALATE", "ESCALATED_CRITIC_FAILURE", 2)]

rows = []
for n, d, inv, f, ed, es, ea in S:
    s = process_invoice(inv, ds, pol, f)
    ok = (s.decision["decision"], s.status, s.attempts) == (ed, es, ea)
    rows.append({"Scenario": n, "Input": d, "Expected": f"{ed} / {es} / {ea} attempt(s)",
                 "Actual": f"{s.decision['decision']} / {s.status} / {s.attempts} attempt(s)", "Result": "PASS" if ok else "FAIL"})
df = pd.DataFrame(rows)
pathlib.Path("docs").mkdir(exist_ok=True)
df.to_csv("docs/test_matrix.csv", index=False)
md = "# Test matrix (generated by running the real workflow)\n\nDataset: synthetic, seed 42. Expected values are hand-written from the policy in `scripts/make_test_matrix.py`.\n\n" + df.to_markdown(index=False) + f"\n\n**{(df.Result=='PASS').sum()}/{len(df)} passed.**\n"
pathlib.Path("docs/test_matrix.md").write_text(md, encoding="utf-8")
print(md[-120:])
